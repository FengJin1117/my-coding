# 输入为224×224×3的图像，使用一个卷积层，包含96个11×11的卷积核，步幅为4，输出的特征图的尺寸为：
# 计算公式：((输入尺寸 - 卷积核尺寸) / 步幅) + 1
# 对于宽度和高度：
输入尺寸 = 224
卷积核尺寸 = 11
步幅 = 4
输出尺寸 = ((输入尺寸 - 卷积核尺寸) / 步幅) + 1
输出尺寸 = ((224 - 11) / 4) + 1
输出尺寸 = (213 / 4) + 1
输出尺寸 = 53.25 + 1
输出尺寸 = 54.25
# 因为输出尺寸必须是整数，所以我们取整：
输出尺寸 = int(输出尺寸)
print(f"输出的特征图的尺寸为: {输出尺寸}×{输出尺寸}×96")

